"""Report exports: the same figures as the screens, as an Excel workbook or a PDF.

A report is first built as a neutral `ReportDocument` (title, filter lines,
tables), then rendered. Both renderers share these rules:
* The file states the organization, report, period, section, branch, who
  generated it and when, and the currency basis.
* Exports are bounded (row limits below) and generated in the request.
* Spreadsheet text is protected against formula injection: values that a
  spreadsheet would treat as a formula are stored as text with a leading
  apostrophe, and every text cell is typed as a string.
"""

from dataclasses import dataclass, field
from decimal import Decimal
from io import BytesIO
from xml.sax.saxutils import escape

from django.utils import timezone

from apps.reports import services

MAX_ROWS = 500
FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r", "\n")


@dataclass
class Column:
    title: str
    kind: str = "text"  # text | money | qty | int
    width: float = 1.0


@dataclass
class Table:
    heading: str
    columns: list
    rows: list = field(default_factory=list)
    total: list | None = None
    note: str = ""
    strong: set = field(default_factory=set)  # indexes of rows to show in bold (subtotals)


@dataclass
class ReportDocument:
    title: str
    slug: str
    organization: str
    filters: list
    basis: str
    tables: list = field(default_factory=list)
    notes: list = field(default_factory=list)


def safe_text(value):
    """Neutralize spreadsheet formula injection (OWASP CSV/formula guidance)."""
    text = "" if value is None else str(value)
    return f"'{text}" if text.startswith(FORMULA_PREFIXES) else text


def _money(value):
    return Decimal(value) if value not in (None, "") else None


def currency_text(by_currency):
    return " · ".join(f"{c} {Decimal(v):,.2f}" for c, v in (by_currency or {}).items())


# ---------- builders ----------


def _filters(meta, generated_by):
    lines = [
        ("Period", f"{meta['period']['from']} to {meta['period']['to']}"),
        ("Section", meta["section"]["name"] if meta["section"] else "All sections"),
        ("Branch", meta["branch"]["name"] if meta["branch"] else "All branches"),
        ("Generated", timezone.localtime().strftime("%d %b %Y %H:%M")),
        ("Generated by", generated_by),
    ]
    return lines


def build_summary(scope, view):
    data = view._summary_payload(scope)
    f, p = data["figures"], data["previous"]["figures"]
    columns = [
        Column("Line", width=2.6),
        Column("This period (USD)", "money"),
        Column(f"Previous (USD) {data['previous']['from']} to {data['previous']['to']}", "money"),
    ]
    rows = []

    def add(label, key, sub=None):
        current, previous = _get(f, key), _get(p, key)
        if current is not None:
            rows.append([label, current, previous])
            if sub:
                rows.append([f"    {sub}", None, None])

    add("Sales", "sales.base", currency_text(f.get("sales", {}).get("by_currency")) or None)
    add("Orders delivered", "orders_delivered.base")
    add("Revenue", "revenue_base")
    add("Cost of goods sold", "cost_of_goods_sold_base")
    add("Gross profit", "gross_profit_base")
    add("Expenses", "expenses.base", currency_text(f.get("expenses", {}).get("by_currency")) or None)
    for category in data["expenses_by_category"]:
        rows.append([f"    {category['name']}", _money(category["base"]), None])
    add("Net profit", "net_profit_base")
    strong = {i for i, r in enumerate(rows) if r[0] in ("Revenue", "Gross profit", "Net profit")}
    tables = [Table("Profit and loss", columns, rows, strong=strong)]
    memo = []
    if "cash_collected" in f:
        memo.append(
            [
                "Cash collected (payments and deposits)",
                _money(f["cash_collected"]["base"]),
                _get(p, "cash_collected.base"),
                currency_text(f["cash_collected"]["by_currency"]),
            ]
        )
    if "purchases" in f:
        memo.append(
            [
                "Stock purchases (not an expense)",
                _money(f["purchases"]["base"]),
                _get(p, "purchases.base"),
                currency_text(f["purchases"]["by_currency"]),
            ]
        )
    if memo:
        tables.append(
            Table(
                "For information (not part of profit)",
                [
                    Column("Line", width=2.6),
                    Column("This period (USD)", "money"),
                    Column("Previous (USD)", "money"),
                    Column("Original currencies", width=1.6),
                ],
                memo,
            )
        )
    if len(data["by_section"]) > 1:
        has_expenses = "expenses_base" in data["by_section"][0]
        tables.append(
            Table(
                "By section",
                [Column("Section", width=2), Column("Revenue (USD)", "money")]
                + ([Column("Expenses (USD)", "money")] if has_expenses else []),
                [
                    [s["name"], _money(s["revenue_base"])] + ([_money(s["expenses_base"])] if has_expenses else [])
                    for s in data["by_section"]
                ],
            )
        )
    notes = [f"{key.replace('_', ' ').capitalize()}: {text}" for key, text in data["definitions"].items()]
    return "Profit and loss", tables, notes


def _get(figures, path):
    value = figures
    for part in path.split("."):
        if not isinstance(value, dict) or part not in value:
            return None
        value = value[part]
    return _money(value)


def build_products(scope, view):
    rows = services.best_products(scope, limit=100)
    costs = view.can("inventory.costs")
    columns = [Column("#", "int", 0.4), Column("Product", width=2.6), Column("Qty sold", "qty"), Column("Revenue (USD)", "money")]
    if costs:
        columns += [Column("Cost (USD)", "money"), Column("Gross profit (USD)", "money")]
    body = [
        [i + 1, r["label"], Decimal(r["quantity"]), _money(r["revenue_base"])]
        + ([_money(r["cost_base"]), _money(r["profit_base"])] if costs else [])
        for i, r in enumerate(rows)
    ]
    return (
        "Best sellers",
        [Table("Best-selling products", columns, body)],
        ["Sale-level discounts are spread over each sale's lines by value."],
    )


def build_customers(scope, view):
    rows = services.best_customers(scope, limit=100)
    columns = [Column("#", "int", 0.4), Column("Customer", width=2.6), Column("Sales and orders", "int"), Column("Revenue (USD)", "money")]
    body = [[i + 1, r["name"], r["transactions"], _money(r["revenue_base"])] for i, r in enumerate(rows)]
    return "Best customers", [Table("Best customers", columns, body)], ["Walk-in sales are not included. Orders count when delivered."]


def _debt_table(heading, debts):
    columns = [Column("Name", width=2.4), Column("Owed (original currency)", width=2), Column("USD equivalent", "money")]
    rows = [[d["name"], currency_text(d["by_currency"]), _money(d["base"])] for d in debts["top"][:MAX_ROWS]]
    return Table(heading, columns, rows, total=["Total", currency_text(debts["by_currency"]), _money(debts["base"])])


def build_debts(scope, view):
    tables = []
    if view.can("sales.view"):
        tables.append(_debt_table("Customers owe you", services.receivables(scope)))
    if view.can("purchases.view"):
        tables.append(_debt_table("You owe suppliers", services.payables(scope)))
    return (
        "Debts",
        tables,
        ["Balances as of the time of export (the period does not apply). USD equivalents use each invoice's own exchange rate."],
    )


def build_stock(scope, view):
    rows = services.stock_valuation(scope)
    summary = services.stock_summary(scope, with_value=True)
    columns = [Column("Section", width=1.4), Column("Category", width=1.6), Column("Units", "qty"), Column("Value (USD)", "money")]
    body = [[r["section"], r["category"], Decimal(r["quantity"]), _money(r["value_base"])] for r in rows[:MAX_ROWS]]
    return (
        "Stock value",
        [Table("Stock value", columns, body, total=["Total", "", None, _money(summary["value_base"])])],
        ["As of the time of export, at moving weighted-average cost."],
    )


BUILDERS = {"summary": build_summary, "products": build_products, "customers": build_customers, "debts": build_debts, "stock": build_stock}


def build_document(report, scope, view, meta):
    title, tables, notes = BUILDERS[report](scope, view)
    user = view.request.user
    for table in tables:
        table.rows = table.rows[:MAX_ROWS]
    return ReportDocument(
        title=title,
        slug=report,
        organization=view.request.membership.organization.name,
        filters=_filters(meta, user.get_full_name() or user.get_username()),
        basis=meta["basis"],
        tables=tables,
        notes=notes,
    )


def filename(document, meta, extension):
    period = meta["period"]
    return f"just-smile-{document.slug}-{period['from']}-to-{period['to']}.{extension}"


