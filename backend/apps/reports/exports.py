def render_xlsx(document):
    """Branded workbook: dark header band with the logo, ink column headers, zebra rows, yellow subtotals."""
    from openpyxl import Workbook
    from openpyxl.drawing.image import Image as XlImage
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    from apps.common import brand

    workbook = Workbook()
    sheet = workbook.active
    sheet.title = document.title[:31]
    sheet.sheet_view.showGridLines = False

    def fill(hex_color):
        return PatternFill("solid", fgColor=hex_color)

    thin = Side(style="thin", color=brand.LINE)
    olive_line = Side(style="medium", color=brand.OLIVE)
    widest = max((len(t.columns) for t in document.tables), default=2)
    band_cols = max(widest, 4) + 1  # one extra column holds the logo

    def text_cell(row, col, value, font=None, cell_fill=None, align=None):
        cell = sheet.cell(row=row, column=col)
        cell.value = safe_text(value)
        cell.data_type = "s"
        if font:
            cell.font = font
        if cell_fill:
            cell.fill = cell_fill
        if align:
            cell.alignment = align
        return cell

    def value_cell(row, col, value, kind, font=None, cell_fill=None):
        if kind == "text" or isinstance(value, str):
            cell = text_cell(row, col, value, font, cell_fill)
            if isinstance(value, str) and value.startswith(" "):
                cell.alignment = Alignment(indent=2)
            return cell
        cell = sheet.cell(row=row, column=col, value=value)
        if value is not None:
            cell.number_format = {
                "money": '#,##0.00;[Color10]-#,##0.00;"–"',
                "qty": "#,##0.###",
                "int": "0",
            }.get(kind, "General")
        if font:
            cell.font = font
        if cell_fill:
            cell.fill = cell_fill
        cell.alignment = Alignment(horizontal="right")
        return cell

    # Header band: organization, report title, tagline; logo on the right.
    band = fill(brand.INK)
    for r in (1, 2, 3):
        for c in range(1, band_cols + 1):
            sheet.cell(row=r, column=c).fill = band
    sheet.row_dimensions[1].height = 22
    sheet.row_dimensions[2].height = 30
    sheet.row_dimensions[3].height = 20
    text_cell(1, 1, document.organization.upper(), Font(bold=True, size=10, color=brand.YELLOW), align=Alignment(vertical="bottom"))
    text_cell(2, 1, document.title, Font(bold=True, size=20, color="FFFFFF"), align=Alignment(vertical="center"))
    text_cell(3, 1, brand.TAGLINE, Font(size=9, color="E8D8C4"), align=Alignment(vertical="top"))
    if brand.LOGO_ON_DARK.exists():
        logo = XlImage(str(brand.LOGO_ON_DARK))
        logo.width = logo.height = 92
        sheet.add_image(logo, f"{get_column_letter(band_cols)}1")
    for c in range(1, band_cols + 1):
        sheet.cell(row=4, column=c).fill = fill(brand.YELLOW)
    sheet.row_dimensions[4].height = 4

    # Filters, as label/value pairs.
    row = 6
    label_font = Font(bold=True, size=9, color=brand.MUTED)
    for label, value in [*document.filters, ("Basis", document.basis)]:
        text_cell(row, 1, label, label_font)
        cell = text_cell(row, 2, value, Font(size=10, color=brand.TEXT))
        if label == "Basis":
            sheet.merge_cells(start_row=row, start_column=2, end_row=row, end_column=band_cols)
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            sheet.row_dimensions[row].height = 30
        row += 1
    row += 1

    widths = {1: 18, 2: 22}
    header_font = Font(bold=True, color="FFFFFF", size=10)
    for table in document.tables:
        heading = text_cell(row, 1, table.heading, Font(bold=True, size=13, color=brand.OLIVE))
        heading.border = Border(bottom=Side(style="medium", color=brand.YELLOW))
        for c in range(2, len(table.columns) + 1):
            sheet.cell(row=row, column=c).border = Border(bottom=Side(style="medium", color=brand.YELLOW))
        sheet.row_dimensions[row].height = 22
        row += 1
        for col, column in enumerate(table.columns, start=1):
            cell = text_cell(row, col, column.title, header_font, fill(brand.DEEP))
            cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="left" if column.kind == "text" else "right")
            widths[col] = max(widths.get(col, 10), min(48, int(15 * column.width)))
        sheet.row_dimensions[row].height = 22
        row += 1
        for index, values in enumerate(table.rows):
            strong = index in table.strong
            row_fill = fill(brand.YELLOW_SOFT) if strong else (fill(brand.PAPER_TINT) if index % 2 else None)
            font = Font(bold=True, color=brand.INK) if strong else Font(color=brand.TEXT)
            for col, (column, value) in enumerate(zip(table.columns, values, strict=True), start=1):
                cell = value_cell(row, col, value, column.kind, font, row_fill)
                cell.border = Border(bottom=thin, top=olive_line if strong else None)
            row += 1
        if table.total:
            for col, (column, value) in enumerate(zip(table.columns, table.total, strict=True), start=1):
                cell = value_cell(row, col, value, column.kind, Font(bold=True, color=brand.INK, size=11), fill("FDF0D8"))
                cell.border = Border(top=olive_line, bottom=olive_line)
            sheet.row_dimensions[row].height = 20
            row += 1
        if not table.rows:
            text_cell(row, 1, "No rows for these filters.", Font(italic=True, color=brand.MUTED))
            row += 1
        if table.note:
            text_cell(row, 1, table.note, Font(italic=True, size=9, color=brand.MUTED))
            row += 1
        row += 1
    for note in document.notes:
        text_cell(row, 1, note, Font(size=9, color=brand.MUTED))
        row += 1
    for col, width in widths.items():
        sheet.column_dimensions[get_column_letter(col)].width = width
    sheet.column_dimensions[get_column_letter(band_cols)].width = max(widths.get(band_cols, 0), 14)

    # Printing: landscape for wide tables, fit to one page wide, branded footer.
    sheet.page_setup.orientation = "landscape" if widest > 4 else "portrait"
    sheet.page_setup.fitToWidth = 1
    sheet.page_setup.fitToHeight = 0
    sheet.sheet_properties.pageSetUpPr.fitToPage = True
    sheet.oddFooter.left.text = f"{document.organization} · {document.title}"
    sheet.oddFooter.right.text = "Page &P of &N"
    workbook.properties.creator = document.organization
    workbook.properties.title = f"{document.organization} - {document.title}"
    out = BytesIO()
    workbook.save(out)
    return out.getvalue()


# ---------- PDF ----------


def _pdf_text(value):
    # Built-in PDF fonts are Latin-1; replace characters they cannot draw.
    text = "" if value is None else str(value)
    text = text.replace("−", "-").replace("—", "-").replace("–", "-").replace("→", "->")
    return escape(text.encode("latin-1", "replace").decode("latin-1"))


def render_pdf(document):
    """Branded PDF: dark header band with logo on every page, ink table headers, zebra rows, yellow subtotals."""
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_RIGHT
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, TableStyle
    from reportlab.platypus import Table as PdfTable

    from apps.common import brand

    def hexc(value):
        return colors.HexColor(f"#{value}")

    ink, deep, olive, yellow = hexc(brand.INK), hexc(brand.DEEP), hexc(brand.OLIVE), hexc(brand.YELLOW)
    soft, tint, line, muted, text_c = hexc(brand.YELLOW_SOFT), hexc(brand.PAPER_TINT), hexc(brand.LINE), hexc(brand.MUTED), hexc(brand.TEXT)

    wide = max((len(t.columns) for t in document.tables), default=0) > 4
    pagesize = landscape(A4) if wide else A4
    page_w, page_h = pagesize
    margin = 15 * mm
    band_h = 30 * mm
    out = BytesIO()
    body = ParagraphStyle("body", fontName="Helvetica", fontSize=9, leading=12, textColor=text_c)
    right = ParagraphStyle("right", parent=body, alignment=TA_RIGHT)
    head = ParagraphStyle("head", parent=body, fontName="Helvetica-Bold", fontSize=8.5, textColor=colors.white)
    head_right = ParagraphStyle("head_right", parent=head, alignment=TA_RIGHT)
    small = ParagraphStyle("small", parent=body, fontSize=7.5, leading=10, textColor=muted)
    indented = ParagraphStyle("indented", parent=body, leftIndent=12, textColor=muted)
    label = ParagraphStyle("label", parent=body, fontName="Helvetica-Bold", fontSize=7, leading=9, textColor=muted)
    value_style = ParagraphStyle("value", parent=body, fontName="Helvetica-Bold", fontSize=9.5, leading=12, textColor=ink)
    heading_style = ParagraphStyle("heading", parent=body, fontName="Helvetica-Bold", fontSize=12, leading=15, textColor=ink)

    def fmt(value, kind):
        if value is None or value == "":
            return ""
        if kind == "money":
            return f"{value:,.2f}"
        if kind == "qty":
            return f"{value.normalize():,f}" if isinstance(value, Decimal) else str(value)
        return str(value)

    available = page_w - 2 * margin
    story = []

    # Filter "cards": label above value, on a soft yellow strip.
    filters = [(k, v) for k, v in document.filters]
    cards = [[Paragraph(_pdf_text(k).upper(), label) for k, _ in filters], [Paragraph(_pdf_text(v), value_style) for _, v in filters]]
    filter_table = PdfTable(cards, colWidths=[available / len(filters)] * len(filters))
    filter_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), soft),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, 0), 7),
                ("BOTTOMPADDING", (0, -1), (-1, -1), 7),
                ("LINEAFTER", (0, 0), (-2, -1), 0.5, hexc("FCDC8B")),
                ("ROUNDEDCORNERS", [6, 6, 6, 6]),
            ]
        )
    )
    story += [filter_table, Spacer(1, 6 * mm)]

    for table in document.tables:
        weights = [c.width for c in table.columns]
        col_widths = [available * w / sum(weights) for w in weights]
        data = [[Paragraph(_pdf_text(c.title), head if c.kind == "text" else head_right) for c in table.columns]]

        def cell(column, value):
            if column.kind != "text":
                return Paragraph(_pdf_text(fmt(value, column.kind)), right)
            text = "" if value is None else str(value)
            return Paragraph(_pdf_text(text.strip()), indented if text.startswith(" ") else body)

        for values in [*table.rows, *([table.total] if table.total else [])]:
            data.append([cell(c, v) for c, v in zip(table.columns, values, strict=True)])
        if not table.rows:
            data.append([Paragraph("No rows for these filters.", small)] + [""] * (len(table.columns) - 1))
        style = [
            ("BACKGROUND", (0, 0), (-1, 0), deep),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING", (0, 0), (-1, -1), 7),
            ("RIGHTPADDING", (0, 0), (-1, -1), 7),
            ("LINEBELOW", (0, 1), (-1, -1), 0.4, line),
            ("ROUNDEDCORNERS", [5, 5, 0, 0]),
        ]
        for index in range(len(table.rows)):
            if index % 2:
                style.append(("BACKGROUND", (0, index + 1), (-1, index + 1), tint))
        if table.total:
            style += [
                ("BACKGROUND", (0, -1), (-1, -1), hexc("FDF0D8")),
                ("LINEABOVE", (0, -1), (-1, -1), 1.2, olive),
                ("LINEBELOW", (0, -1), (-1, -1), 1.2, olive),
            ]
            data[-1] = [Paragraph(f"<b>{p.text}</b>", p.style) if isinstance(p, Paragraph) else p for p in data[-1]]
        for index in table.strong:
            style += [
                ("BACKGROUND", (0, index + 1), (-1, index + 1), soft),
                ("LINEABOVE", (0, index + 1), (-1, index + 1), 0.8, olive),
            ]
            data[index + 1] = [Paragraph(f"<b>{p.text}</b>", p.style) if isinstance(p, Paragraph) else p for p in data[index + 1]]
        pdf_table = PdfTable(data, colWidths=col_widths, repeatRows=1)
        pdf_table.setStyle(TableStyle(style))
        heading = PdfTable(
            [["", Paragraph(_pdf_text(table.heading), heading_style)]],
            colWidths=[3 * mm, available - 3 * mm],
            style=TableStyle(
                [
                    ("BACKGROUND", (0, 0), (0, 0), yellow),
                    ("LEFTPADDING", (1, 0), (1, 0), 6),
                    ("TOPPADDING", (0, 0), (-1, -1), 2),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ]
            ),
        )
        block = [heading, Spacer(1, 2.5 * mm), pdf_table]
        if table.note:
            block += [Spacer(1, 1.5 * mm), Paragraph(_pdf_text(table.note), small)]
        story += [KeepTogether(block[:3]), *block[3:], Spacer(1, 7 * mm)]
    for note in [document.basis, *document.notes]:
        story.append(Paragraph(_pdf_text(note), small))

    generated = dict(document.filters).get("Generated", "")
    org_name = document.organization

    def page(canvas, doc):
        canvas.saveState()
        # Header band with a soft glow and the logo.
        canvas.setFillColor(ink)
        canvas.rect(0, page_h - band_h, page_w, band_h, stroke=0, fill=1)
        canvas.saveState()
        clip = canvas.beginPath()
        clip.rect(0, page_h - band_h, page_w, band_h)
        canvas.clipPath(clip, stroke=0, fill=0)
        canvas.setFillColor(hexc("2B1A10"))
        canvas.circle(page_w - 30 * mm, page_h - 4 * mm, 34 * mm, stroke=0, fill=1)
        canvas.setStrokeColor(hexc("592911"))
        canvas.setLineWidth(6)
        canvas.circle(page_w - 12 * mm, page_h - band_h - 6 * mm, 22 * mm, stroke=1, fill=0)
        canvas.restoreState()
        canvas.setFillColor(yellow)
        canvas.rect(0, page_h - band_h - 1.6 * mm, page_w, 1.6 * mm, stroke=0, fill=1)
        if brand.LOGO_ON_DARK.exists():
            canvas.drawImage(
                str(brand.LOGO_ON_DARK), margin, page_h - band_h + 3.5 * mm, 23 * mm, 23 * mm, mask="auto", preserveAspectRatio=True
            )
        x = margin + 28 * mm
        canvas.setFillColor(yellow)
        canvas.setFont("Helvetica-Bold", 8.5)
        canvas.drawString(x, page_h - 11 * mm, org_name.upper())
        canvas.setFillColor(colors.white)
        canvas.setFont("Helvetica-Bold", 19)
        canvas.drawString(x, page_h - 19.5 * mm, document.title)
        canvas.setFillColor(hexc("E8D8C4"))
        canvas.setFont("Helvetica", 8)
        canvas.drawString(x, page_h - 25 * mm, brand.TAGLINE.replace("·", "-"))
        # Footer.
        canvas.setStrokeColor(yellow)
        canvas.setLineWidth(1.2)
        canvas.line(margin, 13 * mm, page_w - margin, 13 * mm)
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(muted)
